create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  created_at timestamptz not null default now()
);

create table if not exists public.customers (
  id text primary key,
  name text not null,
  phone text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.services (
  id text primary key,
  name text not null,
  price numeric(10,2) not null check (price >= 0),
  type text not null check (type in ('per piece', 'per kg')),
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id text primary key,
  token_no integer unique not null,
  customer_id text not null references public.customers(id),
  date date not null,
  delivery_date date not null,
  status text not null check (status in ('Received', 'Ready', 'Delivered')),
  total numeric(10,2) not null check (total >= 0),
  discount numeric(10,2) not null default 0 check (discount >= 0),
  paid numeric(10,2) not null default 0 check (paid >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id text not null references public.orders(id) on delete cascade,
  service_id text not null references public.services(id),
  qty numeric(10,2) not null check (qty > 0),
  rate numeric(10,2) not null check (rate >= 0),
  amount numeric(10,2) not null check (amount >= 0)
);

create table if not exists public.inventory (
  id text primary key,
  name text not null,
  stock numeric(10,2) not null check (stock >= 0),
  unit text not null,
  min_stock numeric(10,2) not null check (min_stock >= 0),
  created_at timestamptz not null default now()
);

