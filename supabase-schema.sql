create table if not exists public.suppliers (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) > 0),
  contact_person text,
  phone text,
  email text,
  address text,
  registration_number text,
  notes text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.suppliers add column if not exists registration_number text;

create table if not exists public.purchases (
  id uuid primary key default gen_random_uuid(),
  purchase_number text not null unique,
  supplier_id uuid not null references public.suppliers(id),
  purchase_date date not null default current_date,
  invoice_number text,
  total_amount numeric(12,2) not null check (total_amount >= 0),
  amount_paid numeric(12,2) not null default 0 check (amount_paid >= 0),
  balance_amount numeric(12,2) not null check (balance_amount >= 0),
  payment_status text not null check (payment_status in ('Paid', 'Unpaid', 'Partially Paid')),
  purchase_status text not null check (purchase_status in ('Draft', 'Ordered', 'Received', 'Cancelled')),
  notes text,
  created_by uuid references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (amount_paid <= total_amount),
  check (balance_amount = total_amount - amount_paid),
  check (
    (payment_status = 'Paid' and balance_amount = 0)
    or (payment_status = 'Unpaid' and amount_paid = 0 and balance_amount > 0)
    or (payment_status = 'Partially Paid' and amount_paid > 0 and balance_amount > 0)
  )
);

create table if not exists public.purchase_items (
  id uuid primary key default gen_random_uuid(),
  purchase_id uuid not null references public.purchases(id) on delete cascade,
  inventory_id text references public.inventory(id),
  item_name text,
  quantity numeric(12,3) not null check (quantity > 0),
  unit text not null check (length(trim(unit)) > 0),
  unit_cost numeric(12,2) not null check (unit_cost >= 0),
  total_amount numeric(12,2) not null check (total_amount >= 0),
  created_at timestamptz not null default now(),
  check (inventory_id is not null or length(trim(coalesce(item_name, ''))) > 0),
  check (total_amount = round(quantity * unit_cost, 2))
);

create table if not exists public.stock_transactions (
  id uuid primary key default gen_random_uuid(),
  inventory_id text not null references public.inventory(id),
  transaction_type text not null check (
    transaction_type in ('STOCK_IN', 'STOCK_OUT', 'PURCHASE', 'DAMAGE', 'EXPIRED', 'ADJUSTMENT')
  ),
  quantity_change numeric(12,3) not null check (quantity_change <> 0),
  previous_stock numeric(12,3) not null check (previous_stock >= 0),
  new_stock numeric(12,3) not null check (new_stock >= 0),
  supplier_id uuid references public.suppliers(id) on delete set null,
  purchase_id uuid references public.purchases(id) on delete set null,
  transaction_date timestamptz not null default now(),
  notes text,
  created_by uuid references public.users(id) on delete set null,
  check (new_stock = previous_stock + quantity_change)
);

